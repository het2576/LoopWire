def _set_fk(table: str, column: str, ref_table: str, ondelete: str) -> None:
    """v1 foreign keys had no ON DELETE rule; replace them with v2's, using
    the name Postgres gives a fresh database's constraint."""
    for fk in sa.inspect(op.get_bind()).get_foreign_keys(table):
        if fk["constrained_columns"] == [column]:
            op.drop_constraint(fk["name"], table, type_="foreignkey")
    op.create_foreign_key(f"{table}_{column}_fkey", table, ref_table, [column], ["id"], ondelete=ondelete)


def _create_index(name: str, table: str, columns: list[str], unique: bool = False) -> None:
    if name not in _indexes(table):
        op.create_index(name, table, columns, unique=unique)


def _upgrade_v1_schema() -> None:
    from app.url_utils import canonicalize_url

    bind = op.get_bind()

    # users
    _add_column("users", sa.Column("interest_profile_embedding", sa.ARRAY(sa.Float()), nullable=True))
    _add_column("users", sa.Column("interest_vector", sa.ARRAY(sa.Float()), nullable=True))
    _add_column("users", sa.Column("recall_enabled", sa.Boolean(), server_default="true", nullable=False))
    _add_column("users", sa.Column("pending_recall_card_id", sa.Integer(), nullable=True))

    # connection_codes / loopwire_sends
    _set_fk("connection_codes", "user_id", "users", "CASCADE")
    _add_column("loopwire_sends", sa.Column("opened_at", sa.DateTime(timezone=True), nullable=True))
    _set_fk("loopwire_sends", "user_id", "users", "CASCADE")
    _create_index("ix_loopwire_sends_user_id", "loopwire_sends", ["user_id"])

    # saved_items: new columns
    op.alter_column("saved_items", "status", type_=sa.String(length=24), existing_type=sa.String(length=20),
                    existing_nullable=False)
    for column in (
        sa.Column("canonical_url", sa.Text(), nullable=True),  # NOT NULL once backfilled below
        sa.Column("attempts", sa.Integer(), server_default="0", nullable=False),
        sa.Column("processing_started_at", sa.DateTime(timezone=True), nullable=True),
        sa.Column("word_count", sa.Integer(), nullable=True),
        sa.Column("duration_seconds", sa.Integer(), nullable=True),
        sa.Column("summarization_error", sa.Text(), nullable=True),
        sa.Column("embedding", sa.ARRAY(sa.Float()), nullable=True),
        sa.Column("dispatch_rank", sa.Integer(), nullable=True),
        sa.Column("is_exploration", sa.Boolean(), server_default="false", nullable=False),
    ):
        _add_column("saved_items", column)

    # canonical_url: dedupe key for future saves. Existing duplicates are kept
    # (they may have engagement history) but get a suffix so the per-user
    # unique constraint holds; only the oldest copy matches new saves.
    seen: set[tuple[int, str]] = set()
    updates = []
    for item_id, user_id, url in bind.execute(sa.text(
            "SELECT id, user_id, url FROM saved_items WHERE canonical_url IS NULL ORDER BY id")):
        canonical = canonicalize_url(url)
        if (user_id, canonical) in seen:
            canonical = f"{canonical}#loopwire-duplicate-{item_id}"
        seen.add((user_id, canonical))
        updates.append({"id": item_id, "c": canonical})
    if updates:
        bind.execute(sa.text("UPDATE saved_items SET canonical_url = :c WHERE id = :id"), updates)
    op.alter_column("saved_items", "canonical_url", existing_type=sa.Text(), nullable=False)

    # v1's read time was an LLM guess from truncated text; v2 computes it from
    # the word count. (YouTube needs the video duration, which v1 never stored.)
    bind.execute(sa.text(
        "UPDATE saved_items SET word_count = array_length(regexp_split_to_array(btrim(clean_text), '\\s+'), 1) "
        "WHERE word_count IS NULL AND clean_text IS NOT NULL AND btrim(clean_text) <> ''"))
    bind.execute(sa.text(
        f"UPDATE saved_items SET estimated_read_time_minutes = GREATEST(1, ROUND(word_count / {WORDS_PER_MINUTE}.0)) "
        "WHERE word_count > 0 AND type <> 'youtube'"))

    _set_fk("saved_items", "user_id", "users", "CASCADE")
    _set_fk("saved_items", "loopwire_send_id", "loopwire_sends", "SET NULL")
    _create_index("ix_saved_items_user_id", "saved_items", ["user_id"])
    _create_index("ix_saved_items_loopwire_send_id", "saved_items", ["loopwire_send_id"])
    _create_index("ix_saved_items_status", "saved_items", ["status"])
    op.create_unique_constraint("uq_saved_items_user_canonical_url", "saved_items", ["user_id", "canonical_url"])

    # engagement_events. v1 "opened" meant "was sent" (one pixel per item, and
    # every dashboard load), and v1 "skipped" was inferred for unopened emails
    # too; v2 ranking treats both as noise, so they're removed rather than left
    # to skew the interest vector. Clicks are kept, one row per item.
    bind.execute(sa.text("DELETE FROM engagement_events WHERE event_type IN ('opened', 'skipped')"))
    bind.execute(sa.text(
        "DELETE FROM engagement_events a USING engagement_events b "
        "WHERE a.item_id = b.item_id AND a.event_type = b.event_type AND a.id > b.id"))
    _set_fk("engagement_events", "user_id", "users", "CASCADE")
    _set_fk("engagement_events", "item_id", "saved_items", "CASCADE")
    _create_index("ix_engagement_events_user_id", "engagement_events", ["user_id"])
    op.create_unique_constraint("uq_engagement_item_event", "engagement_events", ["item_id", "event_type"])

    # new in v2
    _create_recall_tables()
    # users <-> recall_cards is circular, so this FK is added once both exist.
    op.create_foreign_key('fk_users_pending_recall_card', 'users', 'recall_cards',
                          ['pending_recall_card_id'], ['id'], ondelete='SET NULL')


